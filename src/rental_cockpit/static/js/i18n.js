export function makeI18n(lang) {
  const code = String(lang || "fr").toLowerCase().startsWith("fr") ? "fr" : "en";
  const dict = code === "fr" ? FR : EN;
  const locale = code === "fr" ? "fr-FR" : "en-GB";
  const moneyFmt = new Intl.NumberFormat(locale, { style: "currency", currency: "EUR" });
  const moneyRound = new Intl.NumberFormat(locale, { style: "currency", currency: "EUR", maximumFractionDigits: 0, minimumFractionDigits: 0 });
  const dateLong = new Intl.DateTimeFormat(locale, { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });
  const dateShort = new Intl.DateTimeFormat(locale, { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" });
  const monthFmt = new Intl.DateTimeFormat(locale, { month: "long", year: "numeric", timeZone: "UTC" });
  const toDate = (iso) => new Date(`${iso}T00:00:00Z`);
  const cap = (text) => text.charAt(0).toUpperCase() + text.slice(1);

  const t = (key, params = {}) => {
    const template = dict[key] ?? FR[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) => (params[name] ?? `{${name}}`));
  };
  return {
    lang: code,
    t,
    /** Amount in cents → "1 000 €" for whole euros on big figures, "12,50 €" otherwise. */
    money(cents, { compact = false } = {}) {
      if (cents === null || cents === undefined) return "—";
      const euros = cents / 100;
      return compact && cents % 100 === 0 ? moneyRound.format(euros) : moneyFmt.format(euros);
    },
    dateLong: (iso) => (iso ? dateLong.format(toDate(iso)) : "—"),
    dateShort: (iso) => (iso ? dateShort.format(toDate(iso)) : "—"),
    month: (iso) => cap(monthFmt.format(toDate(iso))),
    monthLower: (iso) => monthFmt.format(toDate(iso)),
    percent(ratio, digits = 0) {
      if (ratio === null || ratio === undefined || !Number.isFinite(ratio)) return "—";
      return new Intl.NumberFormat(locale, { style: "percent", maximumFractionDigits: digits, signDisplay: "exceptZero" }).format(ratio);
    },
    plural(n, one, many) { return t(n > 1 ? many : one, { n }); },
  };
}
