@pytest.mark.parametrize(("name", "raw", "code"), [
    ("script", writer_pdf(lambda w: w.add_js("app.alert('x');")), "pdf_active_content"),
    ("attachment", writer_pdf(lambda w: w.add_attachment("a.txt", b"hello")), "pdf_active_content"),
    ("password", writer_pdf(lambda w: w.encrypt("secret", "owner")), "pdf_encrypted"),
    ("truncated", INVOICE[:300], "pdf_invalid"),
    ("renamed text file", b"Ceci n'est pas un PDF. " * 20, "pdf_invalid"),
    ("too many pages", writer_pdf(lambda w: [w.add_blank_page(10, 10) for _ in range(205)]), "pdf_too_complex"),
    ("too large", b"%PDF-1.4\n" + b"0" * (8 * 1024 * 1024) + b"\n%%EOF\n", "pdf_too_large"),
])
def test_unsafe_or_broken_pdfs_are_refused(name, raw, code):
    with pytest.raises(RCError) as refused:
        documents.inspect_pdf(raw)
    assert refused.value.code == code, name


def test_valid_pdfs_are_accepted_and_read_as_suggestions_only():
    info = documents.inspect_pdf(INVOICE)
    assert (info["pages"], info["text_found"], info["sha256"]) == (1, True, documents.sha256(INVOICE))
    data = {"suppliers": {"sup-1": {"id": "sup-1", "name": "Ménage Essai"}, "sup-2": {"id": "sup-2", "name": "Atelier Essai"}}}
    assert documents.suggestions(info["text"], data) == {"invoice_date": "2026-10-20", "amount": 15000, "invoice_number": "F-018",
                                                         "supplier_id": "sup-1"}
    # A PDF that only restricts printing opens without a password: accepted. A scan without text: nothing proposed.
    scan = documents.inspect_pdf(writer_pdf(lambda w: w.encrypt("", "owner")))
    assert scan["text_found"] is False and documents.suggestions(scan["text"], data) == {}
    english = documents.inspect_pdf(documents.sample_pdf(["Invoice #INV-77", "Invoice date: 3 October 2026", "Amount due EUR 1,089.90"]))
    assert documents.suggestions(english["text"], {}) == {"invoice_date": "2026-10-03", "amount": 108990, "invoice_number": "INV-77"}
    # Never an amount without a label, never a supplier that was not created.
    assert documents.suggestions("Merci de votre visite, 42,00 €. Chez Inconnu SARL.", data) == {}


def test_duplicates_need_more_than_an_amount():
    data = {"properties": {"p1": {"id": "p1", "name": "Gîte"}}, "suppliers": {"s1": {"id": "s1", "name": "Ménage Essai"}}, "categories": {},
            "entries": {"e1": {"id": "e1", "property_id": "p1", "kind": "expense", "supplier_id": "s1", "invoice_number": "F 018",
                               "date": "2026-10-20", "amount": 15000, "label": "Facture"},
                        "e2": {"id": "e2", "property_id": "p1", "kind": "expense", "supplier_id": "s1", "invoice_number": "",
                               "date": "2026-10-25", "amount": 8000, "label": "Ménage"}},
            "documents": {"d1": {"id": "d1", "property_id": "p1", "sha256": "a" * 64, "entry_ids": ["e1"], "supplier_id": "s1",
                                 "invoice_number": "F 018", "invoice_date": "2026-10-20", "amount": 15000}}}
    same_file = documents.duplicates(data, "fr", sha="a" * 64)
    assert [(d["reason"], d["entry_id"]) for d in same_file["certain"]] == [("same_file", "e1")]
    same_ref = documents.duplicates(data, "fr", supplier_id="s1", invoice_number="f-018", invoice_date="2026-11-02", amount=1)
    assert [d["reason"] for d in same_ref["certain"]] == ["same_reference"]
    probable = documents.duplicates(data, "fr", supplier_id="s1", invoice_date="2026-10-25", amount=8000)
    assert (probable["certain"], [d["entry_id"] for d in probable["probable"]]) == ([], ["e2"])
    other_number = documents.duplicates(data, "fr", supplier_id="s1", invoice_number="F-019", invoice_date="2026-10-20", amount=15000)
    assert other_number == {"certain": [], "probable": []}  # same supplier, date and amount, but another number
    assert documents.duplicates(data, "fr", invoice_date="2026-10-25", amount=8000) == {"certain": [], "probable": []}


