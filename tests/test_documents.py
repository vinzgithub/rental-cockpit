def test_rights_on_documents(client):
    pid, _ = setup_property(client)
    hidden = post(client, "/api/properties", {"name": "Bien caché"}, "op-p2")["property"]["id"]
    docs = {}
    for prop, op in ((pid, "a"), (hidden, "b")):
        entry = post(client, "/api/entries", {"property_id": prop, "kind": "expense", "category_id": "cleaning", "label": "Ménage",
                                              "amount": "45", "date": "2026-10-04"}, "op-e" + op)["detail"]
        checked = upload(client, documents.sample_pdf([f"Facture {op}", "Total TTC 45,00 €"]), entry_id=entry["id"]).json()
        docs[prop] = post(client, "/api/documents", {"token": checked["token"], "mode": "attach", "entry_id": entry["id"]}, "op-a" + op)
    db = client.app.state.services.db
    with db.transaction() as conn:
        for name in ("lecteur", "lecteurpdf"):
            conn.execute("INSERT INTO users(username, display_name, password_hash, role, created_at, updated_at) "
                         "VALUES (?, '', ?, 'reader', '2026-10-31', '2026-10-31')", (name, hash_password(PASSWORD)))
            uid = conn.execute("SELECT id FROM users WHERE username = ?", (name,)).fetchone()[0]
            conn.execute("INSERT INTO grants(user_id, property_id, documents) VALUES (?, ?, ?)", (uid, pid, int(name == "lecteurpdf")))

    def sign_in(name):
        reader = TestClient(client.app)
        token = reader.get("/api/session").json()["csrf"]
        reader.headers["X-CSRF-Token"] = reader.post("/api/auth/login", json={"username": name, "password": PASSWORD},
                                                     headers={"X-CSRF-Token": token}).json()["csrf"]
        return reader

    granted_doc = docs[pid]["document"]["id"]
    hidden_doc = docs[hidden]["document"]["id"]
    entry_id = docs[pid]["detail"]["id"]
    # Property only: the expense says a document exists, nothing more.
    reader = sign_in("lecteur")
    detail = reader.get(f"/api/entries/{entry_id}").json()
    assert (detail["documents"], detail["documents_access"], detail["document_list"]) == (1, False, [])
    assert reader.get(f"/api/documents/{granted_doc}/file").status_code == 403
    assert reader.get("/api/documents").json()["documents"] == []
    # Property and its PDFs: readable and downloadable, never the other property, never a change.
    pdf_reader = sign_in("lecteurpdf")
    assert [d["id"] for d in pdf_reader.get("/api/documents").json()["documents"]] == [granted_doc]
    assert pdf_reader.get(f"/api/documents/{granted_doc}/file").status_code == 200
    assert pdf_reader.get(f"/api/documents/{hidden_doc}").status_code == 403
    assert pdf_reader.get(f"/api/documents/{hidden_doc}/file").status_code == 403
    assert pdf_reader.get("/api/documents/doc-0000000000000000/file").status_code == 404
    assert upload(pdf_reader, INVOICE).status_code == 403
    assert pdf_reader.post(f"/api/documents/{granted_doc}/detach", json={"entry_id": entry_id}).status_code == 403
    # Without the CSRF token, nothing is checked or written.
    del client.headers["X-CSRF-Token"]
    assert upload(client, INVOICE).status_code == 403


def test_damaged_original_is_never_served_and_leftovers_are_cleaned(client, tmp_path):
    pid, _ = setup_property(client)
    entry = post(client, "/api/entries", {"property_id": pid, "kind": "expense", "category_id": "cleaning", "label": "Ménage",
                                          "amount": "45", "date": "2026-10-04"}, "op-e")["detail"]
    checked = upload(client, INVOICE, entry_id=entry["id"]).json()
    doc = post(client, "/api/documents", {"token": checked["token"], "mode": "attach", "entry_id": entry["id"]}, "op-a")["document"]
    path = tmp_path / "documents" / f"{doc['sha256']}.pdf"
    path.write_bytes(INVOICE.replace(b"150,00", b"990,00"))
    damaged = client.get(f"/api/documents/{doc['id']}/file")
    assert damaged.status_code == 400 and damaged.json()["code"] == "document_integrity"
    path.unlink()
    assert client.get(f"/api/documents/{doc['id']}/file").json()["code"] == "document_missing_blob"
    # A file left by an interrupted save is removed when the application starts again.
    leftover = tmp_path / "documents" / ("b" * 64 + ".pdf")
    leftover.write_bytes(b"%PDF-1.4 orphan")
    create_app(Config(data_dir=tmp_path))
    assert not leftover.exists()


