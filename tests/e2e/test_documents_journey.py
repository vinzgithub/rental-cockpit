"""Delivery L5 in a real browser: an expense created from a PDF invoice, the same file refused,
a scan attached then detached, and the original downloaded byte for byte.

The PDFs are generated by the test (fictional content only); every date is in the past.
"""
from __future__ import annotations

import io
from pathlib import Path

from pypdf import PdfWriter

from rental_cockpit.engine import documents

INVOICE = documents.sample_pdf(["Ménage Essai — document fictif", "Facture n° F-018", "Date de facture : 20/10/2026",
                                "Ménage 100,00 €", "Linge 40,00 €", "Déplacement 10,00 €", "Total TTC 150,00 €"])


def scan() -> bytes:
    writer = PdfWriter()
    writer.add_blank_page(595, 842)
    buffer = io.BytesIO()
    writer.write(buffer)
    return buffer.getvalue()


def test_invoice_to_expense_duplicate_attach_and_detach(desktop, base_url, tmp_path):
    page = desktop
    invoice = tmp_path / "Facture F-018.pdf"
    invoice.write_bytes(INVOICE)
    scanned = tmp_path / "scan.pdf"
    scanned.write_bytes(scan())
    page.goto(base_url + "/")
    page.locator('.sidebar [data-action="dataset"][data-value="real"]').click()
    page.locator('[data-action="add-property"]').first.click()
    page.locator("#rc-p-name").fill("Gîte d'essai")
    page.locator("dialog[open] [data-save]").click()
    page.locator("dialog[open]").wait_for(state="detached")
    page.locator('.sidebar [data-value="prestataires"]').click()
    page.locator('.pagehead [data-action="supplier-new"]').click()
    page.locator("#rc-sp-name").fill("Ménage Essai")
    page.locator('dialog[open] .check-line:has(input[value="cleaning"])').click()
    page.locator("dialog[open] [data-save]").click()
    page.locator("dialog[open] [data-invoice]").wait_for()
    page.keyboard.press("Escape")

    # « Créer une dépense depuis une facture »: what the PDF says is proposed, marked « À vérifier ».
    page.locator('.sidebar [data-value="justificatifs"]').click()
    page.locator(".empty", has_text="Aucun justificatif").wait_for()
    page.locator('.pagehead [data-action="invoice-import"]').click()
    page.locator("dialog[open] [data-pdf]").set_input_files(str(invoice))
    page.locator("#rc-d-label").wait_for()
    assert page.locator("#rc-d-inv").input_value() == "F-018"
    assert page.locator("#rc-d-amount").input_value() == "150"
    assert page.locator("#rc-d-date").input_value() == "2026-10-20"
    assert page.locator("#rc-d-sup option:checked").text_content() == "Ménage Essai"
    assert page.locator("#rc-d-cat").input_value() == "cleaning"
    assert page.locator("dialog[open] .pill.tiny").count() == 4
    page.locator('dialog[open] .pay-option:has(input[value="unpaid"])').click()
    page.locator("dialog[open] [data-save]").click()
    page.locator("dialog[open] .doc-row").wait_for()
    assert "À payer" in page.locator("dialog[open] .pill-row").text_content()
    # The original comes back byte for byte.
    with page.expect_download() as download:
        page.locator("dialog[open] .doc-row a[download]").click()
    assert Path(download.value.path()).read_bytes() == INVOICE
    page.keyboard.press("Escape")

    # The same file, even renamed, is refused before anything is written.
    renamed = tmp_path / "copie.pdf"
    renamed.write_bytes(INVOICE)
    page.locator('.pagehead [data-action="invoice-import"]').click()
    page.locator("dialog[open] [data-pdf]").set_input_files(str(renamed))
    page.locator("dialog[open] .dup-box", has_text="même fichier").wait_for()
    assert page.locator("dialog[open] [data-save]").is_disabled()
    page.keyboard.press("Escape")
    page.locator(".doc-card").first.wait_for()
    assert page.locator(".doc-card").count() == 1

    # A scan attached to an expense typed by hand: the expense does not change; detached, it is « À compléter ».
    page.locator('.sidebar [data-value="depenses"]').click()
    page.locator('.pagehead [data-action="entry-new"][data-value="expense"]').click()
    page.locator("#rc-e-cat").select_option("cleaning")
    page.locator("#rc-e-label").fill("Ménage de départ")
    page.locator("#rc-e-amount").fill("45")
    page.locator("#rc-e-date").fill("2026-10-04")
    page.locator('dialog[open] .pay-option:has(input[value="unpaid"])').click()
    page.locator("dialog[open] [data-save]").click()
    page.locator("dialog[open] [data-attach]").click()
    page.locator("dialog[open] [data-pdf]").last.set_input_files(str(scanned))
    page.locator("dialog[open] .tip", has_text="conservé tel quel").wait_for()
    page.locator("dialog[open] [data-save]").last.click()
    page.locator("dialog[open] .doc-row").wait_for()
    facts = page.locator("dialog[open] .money-facts").first.inner_text()
    assert "45,00" in facts and "Reste à payer" in facts
    page.locator("dialog[open] [data-detach]").click()
    page.locator("dialog[open] [data-confirm]").click()
    page.locator("dialog[open] .empty", has_text="Aucun justificatif joint").wait_for()
    page.wait_for_function("() => document.querySelectorAll('dialog[open]').length === 1")  # the confirmation has closed
    page.keyboard.press("Escape")
    page.locator("dialog[open]").wait_for(state="detached")

    # « À vérifier » leads to the documents to complete.
    page.locator('.sidebar [data-value="synthese"]').click()
    page.locator('[data-change="period"]').select_option("m:2026-10")
    page.locator('[data-action="go"][data-value="justificatifs"]').first.click()
    page.locator('[data-action="documents-view"][data-value="incomplete"][aria-selected="true"]').wait_for()
    page.locator(".doc-card", has_text="scan.pdf").wait_for()
    assert page.locator(".doc-card").count() == 1


def test_documents_fit_a_phone(phone, base_url):
    """The demo's invoice PDF, from the Justificatifs screen to its page, on a phone."""
    phone.goto(base_url + "/")
    phone.locator(".banner").wait_for()
    phone.locator('.bottomnav [data-value="justificatifs"]').click()
    phone.locator(".doc-card", has_text="F-DEMO-018").wait_for()
    assert phone.evaluate("() => document.documentElement.scrollWidth <= window.innerWidth")
    phone.locator(".doc-card", has_text="F-DEMO-018").click()
    phone.locator("dialog[open] .pill-row").wait_for()
    widths = phone.evaluate("() => { const b = document.querySelector('dialog[open] .dbody'); return [b.scrollWidth, b.clientWidth]; }")
    assert widths[0] <= widths[1], widths
    assert "150,00\xa0€" in phone.locator("dialog[open] .facts-list").first.inner_text()
